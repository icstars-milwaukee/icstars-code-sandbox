#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Build workshops/<slug>/playground.html from that workshop's projects/ folders.

    python tools/build-playground.py              # build every workshop
    python tools/build-playground.py 01-hello-api # build one
    python tools/build-playground.py --check      # fail if any is stale

WHY THIS EXISTS AT ALL
  The real code lives in real folders — workshops/<slug>/projects/<n>-name/.
  Each one opens and runs on its own, straight off disk. That is the source
  of truth and the thing students should end up editing.

  A browser on a file:// path cannot read a folder, so the playground
  cannot discover those files at runtime. This tool copies them into one
  page it can read. That is the whole job: one generated file, derived
  from the folders, instead of three hand-maintained copies of the same
  code. Nothing is generated to *serve* the site.

  Re-run it after you change anything under projects/, and run --check in
  review so a stale playground cannot slip through.

WHAT GOES IN
  Every file under projects/, in folder order. Project order is the folder
  name, which is why they are numbered: 1-, 2-, 3-, 3-...-solution, 4-.
  Each project's label is the <title> of its index.html.
"""

import io
import os
import sys

ROOT = os.path.dirname(os.path.abspath(os.path.join(__file__, "..")))
WORKSHOPS = os.path.join(ROOT, "workshops")

TEXT = (".html", ".htm", ".js", ".css", ".json", ".svg", ".txt", ".md")

BLOCK = '''      <script type="text/plain" data-pg-file="{path}">
{body}
      </script>
'''

PAGE = '''<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Playground — {title}</title>
  <link rel="stylesheet" href="../../css/theme.css">
  <link rel="stylesheet" href="../../css/playground.css">
</head>
<body>

  <header class="ics-header">
    <div class="ics-wrap">
      <a class="ics-back" href="index.html">&larr; {title}</a>
      <div class="ics-brand">i.c.stars<span class="pipe">|</span><span class="star">*</span> Milwaukee</div>
      <h1 class="ics-title">Playground</h1>
      <p class="ics-sub">
        Every project in this workshop, already running. Click a folder to run it,
        click a file to open it, then break it and find out what it was holding up.
      </p>
    </div>
  </header>

  <main class="ics-wrap">
    <span class="ics-step">Break it on purpose</span>

    <p class="pg-note">
      Nothing here can be broken for anybody but you &mdash; it runs in this browser,
      and <strong>Reset all</strong> puts every file back. Your edits survive a refresh,
      so you can come back to them. Each <code>js/main.js</code> ends with a few
      suggestions for what to break first.
    </p>

    <div data-pg data-pg-storage="{slug}">

      <script type="application/json" data-pg-labels>
{labels}
      </script>

{blocks}    </div>

    <p class="ics-footer">
      <!-- GENERATED by tools/build-playground.py from this workshop's projects/
           folders. Edit the real files, then re-run the tool. Hand edits here
           will be overwritten. -->
      The real files are in <code>workshops/{slug}/projects/</code> &mdash; each folder
      opens and runs on its own. This page is generated from them by
      <code>tools/build-playground.py</code>.
      <br>Back to <a href="index.html">{title}</a> &middot;
      <a href="../../index.html">the Code Sandbox</a>
    </p>
  </main>

  <script src="../../js/preview-core.js"></script>
  <script src="../../js/playground.js"></script>

</body>
</html>
'''


def read(path):
    return io.open(path, encoding="utf-8", newline="").read().replace("\r\n", "\n")


def indent(text, n):
    pad = " " * n
    return "\n".join((pad + l) if l.strip() else "" for l in text.split("\n"))


def escape_blocks(text):
    """</script> would end the text/plain block it lives in."""
    return text.replace("</script>", "<\\/script>")


def title_of(src, fallback):
    start = src.find("<title>")
    end = src.find("</title>")
    if start > -1 and end > start:
        return src[start + 7:end].strip()
    return fallback


def workshop_title(folder, slug):
    index = os.path.join(folder, "index.html")
    if os.path.exists(index):
        src = read(index)
        start = src.find('<h1 class="ics-title">')
        if start > -1:
            end = src.find("</h1>", start)
            return src[start + 22:end].strip()
    return slug


def collect(projects_dir, project):
    """Every text file in one project folder, as relative posix paths."""
    out = {}
    base = os.path.join(projects_dir, project)
    for dirpath, dirnames, filenames in os.walk(base):
        dirnames.sort()
        for name in sorted(filenames):
            if not name.lower().endswith(TEXT):
                print("     skipped (not text): %s" % name)
                continue
            full = os.path.join(dirpath, name)
            rel = os.path.relpath(full, base).replace(os.sep, "/")
            out["%s/%s" % (project, rel)] = read(full).rstrip()
    return out


def build(slug):
    folder = os.path.join(WORKSHOPS, slug)
    projects_dir = os.path.join(folder, "projects")
    if not os.path.isdir(projects_dir):
        return None

    projects = sorted(d for d in os.listdir(projects_dir)
                      if os.path.isdir(os.path.join(projects_dir, d)))
    if not projects:
        return None

    blocks = ""
    labels = []
    for project in projects:
        files = collect(projects_dir, project)
        entry = "%s/index.html" % project
        if entry not in files:
            print("     WARNING: %s has no index.html — it will not run" % project)
        labels.append('          "%s": "%s"'
                      % (project, title_of(files.get(entry, ""), project).replace('"', "'")))
        # index.html first: it is the entry point, and the tree shows it first.
        for path in sorted(files, key=lambda p: (not p.endswith("/index.html"), p)):
            blocks += BLOCK.format(path=path, body=indent(escape_blocks(files[path]), 8))

    return PAGE.format(title=workshop_title(folder, slug), slug=slug,
                       labels="        {\n" + ",\n".join(labels) + "\n        }",
                       blocks=blocks)


def main(argv):
    check = "--check" in argv
    wanted = [a for a in argv if not a.startswith("--")]

    slugs = sorted(d for d in os.listdir(WORKSHOPS)
                   if os.path.isdir(os.path.join(WORKSHOPS, d)))
    if wanted:
        slugs = [s for s in slugs if s in wanted]

    stale, built = [], 0
    for slug in slugs:
        page = build(slug)
        if page is None:
            print("  %-22s no projects/ folder, skipped" % slug)
            continue

        out = os.path.join(WORKSHOPS, slug, "playground.html")
        new = page.replace("\n", "\r\n").encode("utf-8")
        old = io.open(out, "rb").read() if os.path.exists(out) else None

        if check:
            if old != new:
                stale.append(slug)
                print("  %-22s STALE" % slug)
            else:
                print("  %-22s ok" % slug)
            continue

        io.open(out, "wb").write(new)
        built += 1
        print("  %-22s %2d projects, %2d files, %6d bytes"
              % (slug, page.count("data-pg-labels") and page.count('": "'),
                 page.count("data-pg-file"), len(new)))

    if check and stale:
        print("\nStale: %s\nRun: python tools/build-playground.py" % ", ".join(stale))
        return 1
    if not check:
        print("\nBuilt %d playground(s)." % built)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
