#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Build workshops/<slug>/playground.html from that workshop's app.

    python tools/build-playground.py              # build every workshop
    python tools/build-playground.py 01-hello-api # build one
    python tools/build-playground.py --check      # fail if any is stale

WHY THIS EXISTS AT ALL
  A workshop IS its app: index.html at the workshop root, its code in
  js/, its styles in css/ if it needs any. That folder opens and runs
  straight off disk, and it is what students end up editing.

  A browser on a file:// path cannot read a folder, so playground.html
  cannot discover those files at runtime. This tool copies them into
  one page it can read. That is the whole job: one generated file,
  derived from the app, instead of a second copy of the code to keep
  in sync. Nothing is generated to *serve* the site.

  Re-run it after you change the app, and run --check in review so a
  stale playground cannot slip through.

WHAT GOES IN
  Every text file in the workshop folder except the deck, the README
  and playground.html itself. In practice: index.html and js/main.js.

WHAT IS SKIPPED
  A folder containing package.json. That is a real npm project - no
  file-inlining preview can do anything with it, because it has to be
  bundled first. Those open in CodeSandbox and carry live: false on
  their card.
"""

import io
import os
import sys

ROOT = os.path.dirname(os.path.abspath(os.path.join(__file__, "..")))
WORKSHOPS = os.path.join(ROOT, "workshops")

TEXT = (".html", ".htm", ".js", ".css", ".json", ".svg")
SKIP_FILES = {"playground.html"}
SKIP_PREFIX = ("REF-",)

BLOCK = '''    <script type="text/plain" data-pg-file="{path}">
{body}
    </script>
'''

PAGE = '''<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Live editor — {title}</title>
  <link rel="stylesheet" href="../../css/theme.css">
  <link rel="stylesheet" href="../../css/playground.css">
</head>
<!-- The editor IS this page: it takes the whole viewport, and nothing
     scrolls except its panes. pg-page is what says so. -->
<body class="pg-page">

  <!-- GENERATED by tools/build-playground.py from the app in
       workshops/{slug}/. Edit the real files, then re-run the tool —
       hand edits here will be overwritten. -->
  <div data-pg
       data-pg-storage="{slug}"
       data-pg-title="{title}"
       data-pg-back="index.html"
       data-pg-root="workshops/{slug}/">

{blocks}  </div>

  <script src="../../js/preview-core.js"></script>
  <script src="../../js/playground.js"></script>

</body>
</html>
'''


def read(path):
    return io.open(path, encoding="utf-8", newline="").read().replace("\r\n", "\n")


def indent(text, n):
    pad = " " * n
    return "\n".join((pad + l) if l.strip() else "" for l in text.split("\n"))


def escape_blocks(text):
    """</script> would end the text/plain block it lives in."""
    return text.replace("</script>", "<\\/script>")


def app_title(folder, slug):
    """The app's own <h1>, which is what it calls itself."""
    index = os.path.join(folder, "index.html")
    if os.path.exists(index):
        src = read(index)
        start = src.find('<h1 class="ics-title">')
        if start > -1:
            end = src.find("</h1>", start)
            return src[start + 22:end].strip()
    return slug


def collect(folder):
    """The app's files, as relative posix paths."""
    out = {}
    for dirpath, dirnames, filenames in os.walk(folder):
        dirnames.sort()
        for name in sorted(filenames):
            if name in SKIP_FILES or name.startswith(SKIP_PREFIX):
                continue
            if not name.lower().endswith(TEXT):
                continue
            full = os.path.join(dirpath, name)
            rel = os.path.relpath(full, folder).replace(os.sep, "/")
            out[rel] = read(full).rstrip()
    return out


def build(slug):
    folder = os.path.join(WORKSHOPS, slug)

    # A workshop with a package.json is a real npm project, not an app that
    # runs off disk - so there is nothing a playground could preview. It has
    # to be bundled first. Those open in CodeSandbox and carry live: false.
    if os.path.exists(os.path.join(folder, "package.json")):
        return None

    files = collect(folder)

    if "index.html" not in files:
        print("     WARNING: %s has no index.html — nothing to run" % slug)
        return None

    # index.html first: it is the entry point, and the sidebar shows
    # it first. Everything else in path order.
    blocks = ""
    for path in sorted(files, key=lambda p: (p != "index.html", p)):
        blocks += BLOCK.format(path=path, body=indent(escape_blocks(files[path]), 6))

    return PAGE.format(title=app_title(folder, slug), slug=slug, blocks=blocks)


def main(argv):
    check = "--check" in argv
    wanted = [a for a in argv if not a.startswith("--")]

    slugs = sorted(d for d in os.listdir(WORKSHOPS)
                   if os.path.isdir(os.path.join(WORKSHOPS, d)))
    if wanted:
        slugs = [s for s in slugs if s in wanted]

    stale, built = [], 0
    for slug in slugs:
        page = build(slug)
        if page is None:
            why = ("npm project - opens in CodeSandbox"
                   if os.path.exists(os.path.join(WORKSHOPS, slug, "package.json"))
                   else "no index.html")
            print("  %-22s skipped (%s)" % (slug, why))
            continue

        out = os.path.join(WORKSHOPS, slug, "playground.html")
        new = page.replace("\n", "\r\n").encode("utf-8")
        old = io.open(out, "rb").read() if os.path.exists(out) else None

        if check:
            if old != new:
                stale.append(slug)
                print("  %-22s STALE" % slug)
            else:
                print("  %-22s ok" % slug)
            continue

        io.open(out, "wb").write(new)
        built += 1
        print("  %-22s %2d files, %6d bytes"
              % (slug, page.count("data-pg-file"), len(new)))

    if check and stale:
        print("\nStale: %s\nRun: python tools/build-playground.py" % ", ".join(stale))
        return 1
    if not check:
        print("\nBuilt %d playground(s)." % built)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
